//! Asset system: files in `assets/` are referenced as `file://name.png` from scripts and instance
//! properties. At compile time Stewdio uploads new or changed assets with Open Cloud, records the
//! result in `Assets.toml`, and rewrites each reference to `rbxassetid://<id>` in the output.
use clap::{Args, Subcommand};
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

use crate::error::*;
use crate::model::*;
use crate::project::Project;
use crate::{auth, fsproj, hjson, http, ui, util};

pub const DIR: &str = "assets";
pub const REGISTRY: &str = "Assets.toml";

// ------------------------------------------------------------------ registry

#[derive(Clone)]
pub struct Entry {
    /// The id used in `rbxassetid://` (the Image id once a Decal has been resolved).
    pub id: u64,
    pub hash: String,
    pub kind: String,
    pub uploaded: u64,
    /// For Decals: the id of the Decal asset that was uploaded.
    pub decal_id: u64,
    /// True once `id` is the Image id behind the Decal (always false for other asset types).
    pub image: bool,
}

#[derive(Default)]
pub struct Registry {
    pub entries: BTreeMap<String, Entry>,
}

impl Registry {
    pub fn load(root: &Path) -> Registry {
        let t: toml::Table = fs::read_to_string(root.join(REGISTRY))
            .ok()
            .and_then(|s| toml::from_str(&s).ok())
            .unwrap_or_default();
        let mut entries = BTreeMap::new();
        if let Some(tbl) = t.get("assets").and_then(|v| v.as_table()) {
            for (k, v) in tbl {
                if let Some(e) = v.as_table() {
                    let id = e.get("id").and_then(|x| x.as_integer()).unwrap_or(0);
                    if id <= 0 {
                        continue;
                    }
                    let kind = e.get("type").and_then(|x| x.as_str()).unwrap_or("").to_string();
                    // entries from older versions only knew the Decal id
                    let decal_id = match e.get("decal_id").and_then(|x| x.as_integer()) {
                        Some(d) if d > 0 => d as u64,
                        _ if kind == "Decal" => id as u64,
                        _ => 0,
                    };
                    entries.insert(
                        k.clone(),
                        Entry {
                            id: id as u64,
                            hash: e.get("hash").and_then(|x| x.as_str()).unwrap_or("").to_string(),
                            kind,
                            uploaded: e.get("uploaded").and_then(|x| x.as_integer()).unwrap_or(0) as u64,
                            decal_id,
                            image: e.get("image").and_then(|x| x.as_bool()).unwrap_or(false),
                        },
                    );
                }
            }
        }
        Registry { entries }
    }

    pub fn save(&self, root: &Path) -> std::io::Result<()> {
        let mut assets = toml::Table::new();
        for (k, e) in &self.entries {
            let mut t = toml::Table::new();
            t.insert("id".to_string(), toml::Value::Integer(e.id as i64));
            t.insert("hash".to_string(), toml::Value::String(e.hash.clone()));
            t.insert("type".to_string(), toml::Value::String(e.kind.clone()));
            t.insert("uploaded".to_string(), toml::Value::Integer(e.uploaded as i64));
            if e.kind == "Decal" {
                t.insert("decal_id".to_string(), toml::Value::Integer(e.decal_id as i64));
                t.insert("image".to_string(), toml::Value::Boolean(e.image));
            }
            assets.insert(k.clone(), toml::Value::Table(t));
        }
        let mut top = toml::Table::new();
        top.insert("assets".to_string(), toml::Value::Table(assets));
        let body = toml::to_string(&top).map_err(|e| std::io::Error::new(std::io::ErrorKind::Other, e.to_string()))?;
        fs::write(
            root.join(REGISTRY),
            format!("# Generated by Stewdio: maps files in assets/ to uploaded Roblox asset IDs.\n# Commit this file so teammates and CI reuse the uploads.\n\n{body}"),
        )
    }
}

// --------------------------------------------------------------------- files

pub fn known_files(root: &Path) -> HashSet<String> {
    fn go(dir: &Path, rel: &str, out: &mut HashSet<String>) {
        let rd = match fs::read_dir(dir) {
            Ok(r) => r,
            Err(_) => return,
        };
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            if name.starts_with('.') {
                continue;
            }
            let p = e.path();
            let child = if rel.is_empty() { name.clone() } else { format!("{rel}/{name}") };
            if p.is_dir() {
                go(&p, &child, out);
            } else {
                out.insert(child);
            }
        }
    }
    let mut out = HashSet::new();
    go(&root.join(DIR), "", &mut out);
    out
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

pub fn file_hash(path: &Path) -> std::io::Result<String> {
    let data = fs::read(path)?;
    Ok(format!("{}-{}", hex(&util::hash16(&data)), data.len()))
}

/// Roblox asset type and MIME type for a file, decided by its extension.
pub fn type_for(rel: &str) -> Result<(&'static str, &'static str), String> {
    let ext = Path::new(rel).extension().and_then(|e| e.to_str()).unwrap_or("").to_lowercase();
    match ext.as_str() {
        "png" => Ok(("Decal", "image/png")),
        "jpg" | "jpeg" => Ok(("Decal", "image/jpeg")),
        "bmp" => Ok(("Decal", "image/bmp")),
        "tga" => Ok(("Decal", "image/tga")),
        "mp3" => Ok(("Audio", "audio/mpeg")),
        "ogg" => Ok(("Audio", "audio/ogg")),
        "fbx" => Ok(("Model", "model/fbx")),
        "mp4" => Ok(("Video", "video/mp4")),
        "mov" => Ok(("Video", "video/mov")),
        _ => Err(format!("'{rel}': unsupported asset type (supported: png, jpg, bmp, tga, mp3, ogg, fbx, mp4, mov)")),
    }
}

// ------------------------------------------------------------------ scanning

const STOP: &[char] = &['"', '\'', '`', '\n', '\r', ')', ']', '}', ',', ';', '<', '>'];

pub struct Ref {
    pub start: usize,
    pub end: usize,
    /// Ok(path inside assets/) or Err(text that matched no file)
    pub target: Result<String, String>,
}

/// Find `file://...` references in `text`. Paths may contain spaces; the longest prefix that is an
/// existing asset wins.
pub fn scan(text: &str, known: &HashSet<String>) -> Vec<Ref> {
    let mut out = Vec::new();
    let mut i = 0;
    while let Some(pos) = text[i..].find("file://") {
        let start = i + pos;
        let body = start + 7;
        let run_end = text[body..].find(|c: char| STOP.contains(&c)).map(|p| body + p).unwrap_or(text.len());
        let mut cand_end = run_end;
        i = run_end.max(body);
        loop {
            let cand = text[body..cand_end].trim_end();
            if cand.is_empty() {
                break;
            }
            if known.contains(cand) {
                out.push(Ref { start, end: body + cand.len(), target: Ok(cand.to_string()) });
                i = body + cand.len();
                break;
            }
            match text[body..cand_end].rfind(' ') {
                Some(sp) => cand_end = body + sp,
                None => {
                    out.push(Ref { start, end: run_end, target: Err(text[body..run_end].trim().to_string()) });
                    break;
                }
            }
        }
        if i <= start {
            i = start + 7;
        }
    }
    out
}

#[derive(Default)]
pub struct Collected {
    pub refs: BTreeSet<String>,
    pub missing: Vec<String>,
}

fn note(text: &str, here: &str, known: &HashSet<String>, c: &mut Collected) {
    for r in scan(text, known) {
        match r.target {
            Ok(p) => {
                c.refs.insert(p);
            }
            Err(raw) => c.missing.push(format!("{here}: asset 'file://{raw}' was not found in {DIR}/")),
        }
    }
}

fn note_value(v: &PropValue, here: &str, known: &HashSet<String>, c: &mut Collected) {
    match v {
        PropValue::Text(t) => note(t, here, known, c),
        PropValue::Fields(f) => {
            for (_, x) in f {
                note_value(x, here, known, c);
            }
        }
    }
}

fn walk_collect(inst: &Instance, parent: &str, known: &HashSet<String>, c: &mut Collected) {
    let here = if parent.is_empty() { inst.name.clone() } else { format!("{parent}/{}", inst.name) };
    if let Some(src) = &inst.source {
        note(src, &here, known, c);
    }
    for p in &inst.properties {
        if p.ty != "BinaryString" {
            note_value(&p.value, &here, known, c);
        }
    }
    for ch in &inst.children {
        walk_collect(ch, &here, known, c);
    }
}

pub fn collect(roots: &[Instance], known: &HashSet<String>) -> Collected {
    let mut c = Collected::default();
    for r in roots {
        walk_collect(r, "", known, &mut c);
    }
    c
}

fn rewrite_text(t: &mut String, known: &HashSet<String>, ids: &HashMap<String, u64>) {
    let refs = scan(t, known);
    if refs.is_empty() {
        return;
    }
    let mut out = String::with_capacity(t.len());
    let mut last = 0;
    for r in refs {
        if let Ok(p) = &r.target {
            if let Some(id) = ids.get(p) {
                out.push_str(&t[last..r.start]);
                out.push_str(&format!("rbxassetid://{id}"));
                last = r.end;
            }
        }
    }
    out.push_str(&t[last..]);
    *t = out;
}

fn rewrite_value(v: &mut PropValue, known: &HashSet<String>, ids: &HashMap<String, u64>) {
    match v {
        PropValue::Text(t) => rewrite_text(t, known, ids),
        PropValue::Fields(f) => {
            for (_, x) in f.iter_mut() {
                rewrite_value(x, known, ids);
            }
        }
    }
}

/// Replace every `file://x` with `rbxassetid://<id>` using `ids`.
pub fn rewrite(roots: &mut [Instance], known: &HashSet<String>, ids: &HashMap<String, u64>) {
    for r in roots.iter_mut() {
        if let Some(s) = &mut r.source {
            rewrite_text(s, known, ids);
        }
        for p in r.properties.iter_mut() {
            if p.ty != "BinaryString" {
                rewrite_value(&mut p.value, known, ids);
            }
        }
        rewrite(&mut r.children, known, ids);
    }
}

