#[derive(Clone)]
pub enum Creator {
    User(String),
    Group(String),
}

fn json_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn display_name(rel: &str) -> String {
    let stem = Path::new(rel).file_stem().and_then(|s| s.to_str()).unwrap_or("asset");
    let cleaned: String = stem
        .chars()
        .map(|c| if c.is_alphanumeric() || matches!(c, ' ' | '-' | '_' | '.') { c } else { '_' })
        .take(50)
        .collect();
    if cleaned.trim().is_empty() {
        "asset".to_string()
    } else {
        cleaned
    }
}

fn credentials(project: &Project, profile: Option<&str>) -> CliResult<(String, Creator)> {
    let key = auth::current_key(profile).ok_or_else(|| {
        CliError::new(
            AUTH,
            "Roblox authentication failed: no API key configured (run `stewdio auth login`); assets need uploading",
        )
    })?;
    let a = &project.file.assets;
    let creator = if let Some(g) = a.creator_group_id {
        Creator::Group(g.to_string())
    } else if let Some(u) = a.creator_user_id {
        Creator::User(u.to_string())
    } else if let Some(u) = auth::authorized_user(&key) {
        Creator::User(u)
    } else {
        return Err(CliError::new(
            GENERAL,
            "Cannot tell who should own uploaded assets. Run `stewdio settings set assets.creator_user_id <your user id>` (or assets.creator_group_id)",
        ));
    };
    Ok((key, creator))
}

fn op_result(v: &hjson::Value) -> Option<Result<u64, String>> {
    if v.get("done").and_then(|x| x.as_bool()) != Some(true) {
        return None;
    }
    if let Some(err) = v.get("error") {
        let msg = err.get("message").and_then(|m| m.as_str()).unwrap_or("the upload was rejected");
        return Some(Err(msg.to_string()));
    }
    let id = v.get("response").and_then(|r| r.get("assetId"));
    Some(match id {
        Some(hjson::Value::Str(s)) => s.parse::<u64>().map_err(|_| "invalid asset id in response".to_string()),
        Some(hjson::Value::Number(n)) => n.parse::<u64>().map_err(|_| "invalid asset id in response".to_string()),
        _ => Err("the response had no assetId".to_string()),
    })
}

fn api_error(status: u16, body: &[u8]) -> CliError {
    let msg = hjson::parse(&String::from_utf8_lossy(body))
        .ok()
        .and_then(|v| v.get("message").and_then(|m| m.as_str().map(|x| x.to_string())))
        .unwrap_or_else(|| String::from_utf8_lossy(body).chars().take(200).collect());
    match status {
        401 => CliError::new(AUTH, "Roblox authentication failed (HTTP 401): the API key is invalid, disabled or expired"),
        403 => CliError::new(
            AUTH,
            "Permission denied (HTTP 403): the API key needs the Assets API permissions asset:read and asset:write, and your IP must be allowed",
        ),
        429 => CliError::new(GENERAL, "Rate limited by Roblox (HTTP 429): try again in a minute"),
        s => CliError::new(GENERAL, format!("Roblox rejected the asset upload (HTTP {s}): {msg}")),
    }
}

/// Upload one file with the Open Cloud Assets API. Returns (asset id, asset type).
pub fn upload_asset(key: &str, creator: &Creator, file: &Path, rel: &str) -> CliResult<(u64, String)> {
    let (kind, mime) = type_for(rel).map_err(|e| CliError::new(UNSUPPORTED, e))?;
    let creator_json = match creator {
        Creator::User(id) => format!("{{\"userId\":{}}}", json_str(id)),
        Creator::Group(id) => format!("{{\"groupId\":{}}}", json_str(id)),
    };
    let req = format!(
        "{{\"assetType\":{},\"displayName\":{},\"description\":{},\"creationContext\":{{\"creator\":{}}}}}",
        json_str(kind),
        json_str(&display_name(rel)),
        json_str("Uploaded by Stewdio"),
        creator_json
    );
    let tmp = std::env::temp_dir().join(format!("stewdio-asset-{}-{}.json", std::process::id(), util::now_secs()));
    fs::write(&tmp, req)?;
    let forms = vec![
        format!("request=<\"{}\";type=application/json", tmp.display()),
        format!("fileContent=@\"{}\";type={}", file.display(), mime),
    ];
    let resp = http::request_form("POST", "https://apis.roblox.com/assets/v1/assets", &[("x-api-key", key.to_string())], &forms);
    let _ = fs::remove_file(&tmp);
    let resp = resp.map_err(|e| CliError::new(GENERAL, e))?;
    if resp.status != 200 {
        return Err(api_error(resp.status, &resp.body));
    }
    let v = hjson::parse(&String::from_utf8_lossy(&resp.body))
        .map_err(|_| CliError::new(PARSE, "Unexpected response from the Assets API"))?;
    if let Some(r) = op_result(&v) {
        return r.map(|id| (id, kind.to_string())).map_err(|e| CliError::new(GENERAL, format!("{rel}: {e}")));
    }
    let op = v
        .get("path")
        .and_then(|p| p.as_str())
        .and_then(|p| p.rsplit('/').next())
        .ok_or_else(|| CliError::new(PARSE, "The Assets API did not return an operation"))?
        .to_string();
    let url = format!("https://apis.roblox.com/assets/v1/operations/{op}");
    for _ in 0..120 {
        std::thread::sleep(Duration::from_secs(1));
        let r = http::request("GET", &url, &[("x-api-key", key.to_string())], None, None)
            .map_err(|e| CliError::new(GENERAL, e))?;
        if r.status != 200 {
            return Err(api_error(r.status, &r.body));
        }
        if let Ok(v) = hjson::parse(&String::from_utf8_lossy(&r.body)) {
            if let Some(res) = op_result(&v) {
                return res.map(|id| (id, kind.to_string())).map_err(|e| CliError::new(GENERAL, format!("{rel}: {e}")));
            }
        }
    }
    Err(CliError::new(GENERAL, format!("{rel}: timed out waiting for Roblox to process the upload")))
}

/// Asset ids mentioned in text such as `http://www.roblox.com/asset/?id=123` or `rbxassetid://123`.
fn ids_in(text: &str) -> Vec<u64> {
    let lower = text.to_lowercase();
    let mut out = Vec::new();
    for pat in ["rbxassetid://", "asset/?id=", "assetid="] {
        let mut i = 0;
        while let Some(p) = lower[i..].find(pat) {
            let start = i + p + pat.len();
            let digits: String = lower[start..].chars().take_while(|c| c.is_ascii_digit()).collect();
            if let Ok(n) = digits.parse::<u64>() {
                out.push(n);
            }
            i = start;
        }
    }
    out
}

fn push_texts(v: &PropValue, out: &mut Vec<String>) {
    match v {
        PropValue::Text(t) => out.push(t.clone()),
        PropValue::Fields(f) => {
            for (_, x) in f {
                push_texts(x, out);
            }
        }
    }
}

fn walk_texts(i: &Instance, out: &mut Vec<String>) {
    for p in &i.properties {
        push_texts(&p.value, out);
    }
    for c in &i.children {
        walk_texts(c, out);
    }
}

/// A Decal asset is a tiny model whose Texture points at the real Image asset; find that id.
pub fn image_id_from_decal(data: &[u8], decal: u64) -> Option<u64> {
    let mut texts: Vec<String> = Vec::new();
    if data.starts_with(b"<roblox!") {
        if let Ok(d) = crate::rbxl::decode(data) {
            for r in &d.roots {
                walk_texts(r, &mut texts);
            }
        }
    } else {
        texts.push(String::from_utf8_lossy(data).to_string());
    }
    texts.iter().flat_map(|t| ids_in(t)).find(|n| *n != decal && *n > 0)
}

/// Look up the Image id behind a Decal id (needs the key's `legacy-asset:manage` permission).
/// Right after an upload the file may not be available yet, so `attempts` > 1 retries.
pub fn resolve_image(key: &str, decal: u64, attempts: usize) -> CliResult<u64> {
    let mut last: Option<CliError> = None;
    for n in 0..attempts.max(1) {
        if n > 0 {
            std::thread::sleep(Duration::from_secs(2));
        }
        match crate::remote::download_asset(decal, None, key, "Decal") {
            Ok(data) => match image_id_from_decal(&data, decal) {
                Some(id) => return Ok(id),
                None => last = Some(CliError::new(PARSE, "could not find the image id inside the decal")),
            },
            Err(e) => {
                if e.code == AUTH {
                    return Err(e); // permission problems will not fix themselves
                }
                last = Some(e);
            }
        }
    }
    Err(last.unwrap_or_else(|| CliError::new(GENERAL, "image id lookup failed")))
}

/// Turn a stored Decal id into its Image id. Returns a warning message when that was not possible.
fn convert_entry(root: &Path, reg: &mut Registry, rel: &str, key: &str, attempts: usize) -> Option<String> {
    let decal = reg.entries.get(rel)?.decal_id;
    match resolve_image(key, decal, attempts) {
        Ok(img) => {
            if let Some(e) = reg.entries.get_mut(rel) {
                e.id = img;
                e.image = true;
            }
            if let Err(e) = reg.save(root) {
                return Some(format!("{rel}: could not save {REGISTRY}: {e}"));
            }
            None
        }
        Err(e) => Some(format!("{rel}: using the Decal id because the Image id could not be resolved ({})", e.message)),
    }
}

pub struct SyncOpts {
    pub allow_upload: bool,
    pub force: bool,
    pub quiet: bool,
    pub profile: Option<String>,
}

pub struct SyncResult {
    pub ids: HashMap<String, u64>,
    pub uploaded: usize,
}

/// Make sure every asset in `wanted` has an up-to-date upload; returns their asset ids.
/// Images are uploaded as Decals and then converted to the Image ids that `rbxassetid://` expects.
pub fn ensure_uploaded(project: &Project, wanted: &BTreeSet<String>, opts: &SyncOpts) -> CliResult<SyncResult> {
    let mut reg = Registry::load(&project.root);
    let mut ids = HashMap::new();
    let mut uploaded = 0;
    let mut cred: Option<(String, Creator)> = None;
    let mut no_key_for: Vec<String> = Vec::new();
    for rel in wanted {
        let path = project.root.join(DIR).join(rel);
        let hash = file_hash(&path)
            .map_err(|e| CliError::new(GENERAL, format!("cannot read {}: {e}", path.display())))?;
        let unchanged = !opts.force && reg.entries.get(rel).map(|e| e.hash == hash).unwrap_or(false);
        if unchanged {
            let pending = reg.entries.get(rel).map(|e| e.kind == "Decal" && !e.image).unwrap_or(false);
            if pending {
                let key = match &cred {
                    Some((k, _)) => Some(k.clone()),
                    None => auth::current_key(opts.profile.as_deref()),
                };
                match key {
                    Some(k) => {
                        if !opts.quiet {
                            ui::step(&format!("Resolving the Image id for {rel}..."));
                        }
                        if let Some(w) = convert_entry(&project.root, &mut reg, rel, &k, 1) {
                            ui::warning(&w);
                        }
                    }
                    None => no_key_for.push(rel.clone()),
                }
            }
            if let Some(e) = reg.entries.get(rel) {
                ids.insert(rel.clone(), e.id);
            }
            continue;
        }
        if !opts.allow_upload {
            return Err(CliError::new(
                GENERAL,
                format!("Asset '{rel}' is new or changed but uploading is disabled (--no-upload); run `stewdio assets sync`"),
            ));
        }
        let (key, creator) = match &cred {
            Some(c) => c.clone(),
            None => {
                let c = credentials(project, opts.profile.as_deref())?;
                cred = Some(c.clone());
                c
            }
        };
        if !opts.quiet {
            ui::step(&format!("Uploading asset {rel}..."));
        }
        let (id, kind) = upload_asset(&key, &creator, &path, rel)?;
        let decal_id = if kind == "Decal" { id } else { 0 };
        reg.entries.insert(
            rel.clone(),
            Entry { id, hash, kind: kind.clone(), uploaded: util::now_secs(), decal_id, image: false },
        );
        reg.save(&project.root)?;
        if kind == "Decal" {
            if !opts.quiet {
                ui::step(&format!("Resolving the Image id for {rel}..."));
            }
            if let Some(w) = convert_entry(&project.root, &mut reg, rel, &key, 10) {
                ui::warning(&w);
            }
        }
        if let Some(e) = reg.entries.get(rel) {
            ids.insert(rel.clone(), e.id);
        }
        uploaded += 1;
    }
    if !no_key_for.is_empty() {
        ui::warning(&format!(
            "{} image asset(s) still use Decal ids because no API key is configured to look up their Image ids (run `stewdio auth login`)",
            no_key_for.len()
        ));
    }
    Ok(SyncResult { ids, uploaded })
}

// ------------------------------------------------------------------ command

#[derive(Args)]
pub struct AssetsArgs {
    #[command(subcommand)]
    pub cmd: Option<AssetsCmd>,
}

#[derive(Subcommand)]
pub enum AssetsCmd {
    /// Show which assets are uploaded, changed, new, unused or missing
    Status,
    /// List uploaded assets from Assets.toml
    List,
    /// Upload new or changed assets now (referenced ones by default)
    Sync {
        /// Upload every file in assets/, not just referenced ones
        #[arg(long)]
        all: bool,
        /// Upload again even if the file did not change
        #[arg(long)]
        force: bool,
        /// Authentication profile to use
        #[arg(long)]
        profile: Option<String>,
    },
    /// Forget an uploaded asset so it is uploaded again next time
    Forget { path: String },
}

pub fn run(a: AssetsArgs) -> CliResult<()> {
    let project = Project::current()?;
    let known = known_files(&project.root);
    let loaded = fsproj::load(&project.root, project.is_model());
    let col = collect(&loaded.roots, &known);
    let mut reg = Registry::load(&project.root);
    match a.cmd.unwrap_or(AssetsCmd::Status) {
        AssetsCmd::Status => {
            let mut files: Vec<&String> = known.iter().collect();
            files.sort();
            if files.is_empty() {
                println!("No files in {DIR}/ yet. Put files there and reference them as file://name.png");
            }
            for f in files {
                let used = col.refs.contains(f);
                let state = match reg.entries.get(f.as_str()) {
                    Some(e) => match file_hash(&project.root.join(DIR).join(f)) {
                        Ok(h) if h == e.hash => {
                            if e.kind == "Decal" && !e.image {
                                format!("uploaded  rbxassetid://{} (Decal id; Image id not resolved yet)", e.id)
                            } else {
                                format!("uploaded  rbxassetid://{}", e.id)
                            }
                        }
                        _ => "changed since upload".to_string(),
                    },
                    None => "not uploaded".to_string(),
                };
                println!("{DIR}/{f:<32} {state}{}", if used { "" } else { "  (unused)" });
            }
            for m in &col.missing {
                ui::error(m);
            }
            for k in reg.entries.keys() {
                if !known.contains(k) {
                    ui::warning(&format!("Assets.toml lists '{k}' but the file no longer exists"));
                }
            }
        }
        AssetsCmd::List => {
            if reg.entries.is_empty() {
                println!("Nothing uploaded yet");
            }
            for (k, e) in &reg.entries {
                let note = if e.kind == "Decal" {
                    if e.image { format!(", decal {}", e.decal_id) } else { ", decal id (image not resolved)".to_string() }
                } else {
                    String::new()
                };
                println!("{k:<32} rbxassetid://{:<14} {} ({}){note}", e.id, e.kind, util::fmt_time(e.uploaded));
            }
        }
        AssetsCmd::Sync { all, force, profile } => {
            if !col.missing.is_empty() {
                for m in &col.missing {
                    ui::error(m);
                }
                return Err(CliError::new(PROJECT, "Some file:// references point to files that do not exist"));
            }
            let mut wanted: BTreeSet<String> = if all { known.iter().cloned().collect() } else { col.refs.clone() };
            if all {
                wanted.retain(|f| match type_for(f) {
                    Ok(_) => true,
                    Err(e) => {
                        ui::warning(&format!("skipping {e}"));
                        false
                    }
                });
            }
            if wanted.is_empty() {
                println!("Nothing to upload");
                return Ok(());
            }
            let res = ensure_uploaded(
                &project,
                &wanted,
                &SyncOpts { allow_upload: true, force, quiet: false, profile },
            )?;
            ui::success(&format!("Done: {} uploaded, {} already up to date", res.uploaded, wanted.len() - res.uploaded));
        }
        AssetsCmd::Forget { path } => {
            if reg.entries.remove(&path).is_none() {
                return Err(CliError::new(ARGS, format!("'{path}' is not in {REGISTRY}")));
            }
            reg.save(&project.root)?;
            println!("Forgot {path}; it will be uploaded again the next time it is needed");
        }
    }
    Ok(())
}

pub fn dir_path(root: &Path) -> PathBuf {
    root.join(DIR)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn known(list: &[&str]) -> HashSet<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn finds_and_rewrites_references() {
        let k = known(&["sprite.png", "ui/my icon.png"]);
        let text = "local a = \"file://sprite.png\"\nlocal b = 'file://ui/my icon.png'\nprint(\"file://nope.png\")";
        let refs = scan(text, &k);
        assert_eq!(refs.len(), 3);
        assert_eq!(refs[0].target, Ok("sprite.png".to_string()));
        assert_eq!(refs[1].target, Ok("ui/my icon.png".to_string()));
        assert!(refs[2].target.is_err());
        let mut ids = HashMap::new();
        ids.insert("sprite.png".to_string(), 111u64);
        ids.insert("ui/my icon.png".to_string(), 222u64);
        let mut t = text.to_string();
        rewrite_text(&mut t, &k, &ids);
        assert!(t.contains("\"rbxassetid://111\""));
        assert!(t.contains("'rbxassetid://222'"));
        assert!(t.contains("file://nope.png"));
    }

    #[test]
    fn finds_image_id_in_decal_xml() {
        let xml = "<roblox><Item class=\"Decal\"><Properties><Content name=\"Texture\"><url>http://www.roblox.com/asset/?id=987654</url></Content></Properties></Item></roblox>";
        assert_eq!(image_id_from_decal(xml.as_bytes(), 1), Some(987654));
        assert_eq!(image_id_from_decal(b"<roblox></roblox>", 1), None);
        assert_eq!(ids_in("rbxassetid://12 and Asset/?ID=34"), vec![12, 34]);
    }

    #[test]
    fn registry_round_trips() {
        let dir = std::env::temp_dir().join(format!("stewdio-reg-test-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        let mut r = Registry::default();
        r.entries.insert("a b.png".to_string(), Entry { id: 42, hash: "h-1".to_string(), kind: "Decal".to_string(), uploaded: 7, decal_id: 41, image: true });
        r.save(&dir).unwrap();
        let back = Registry::load(&dir);
        assert_eq!(back.entries["a b.png"].id, 42);
        assert_eq!(back.entries["a b.png"].decal_id, 41);
        assert!(back.entries["a b.png"].image);
        let _ = fs::remove_dir_all(&dir);
    }
}
